#!/usr/bin/env python3
"""
修正版：解決 systemctl pager (less) 卡死問題，精確緩解 PHP-FPM
"""

import sys
import shlex
import re
from opsfeast import Instance, RootUnavailableError

TARGET_HOST = "rms3"
DROP_IN_INI = "99-security-cve-mitigation.ini"

def run_fpm_mitigation(dry_run: bool = False):
    print(f"[*] 正在初始化 OpsFeast Instance...")
    instance = Instance.open(".")
    profile = instance.profile()
    print(f"[*] 使用 Profile: {profile.name} (連線目標: {TARGET_HOST})")
    print(f"[*] 執行模式: {'[DRY RUN - 僅檢查]' if dry_run else '[正式修補]'}\n")

    with profile.recipe(TARGET_HOST, timeout=60) as recipe:
        with recipe.root() as root:
            # 關鍵防護：全域禁用 systemd / less 分頁器
            root("export SYSTEMD_PAGER=cat PAGER=cat", check=False)

            # 1. 動態鎖定實際運行的 PHP-FPM systemd 服務
            # 加上 --no-pager 避免卡住
            svc_res = root(
                "systemctl --no-pager list-units --type=service --state=running --no-legend --plain "
                "| grep -oE '(php[0-9.]*-fpm|php-fpm)\\.service' | head -n 1",
                check=False
            )
            fpm_service = svc_res.stdout.strip()
            if not fpm_service:
                raise RuntimeError("未在目標主機上偵測到任何運行中的 PHP-FPM 服務！")
            print(f"[✓] 偵測到正在運行的 FPM 服務: {fpm_service}")

            # 2. 獲取實際運行的 FPM Binary（加上 --no-pager）
            exec_res = root(f"systemctl --no-pager show {shlex.quote(fpm_service)} -p ExecStart", check=False)
            m = re.search(r"path=([^ ;]+)", exec_res.stdout) if exec_res.stdout else None

            if m:
                fpm_bin = m.group(1)
            else:
                # Fallback: 若 systemctl 無法解析，從 ps 進程直接取得 binary
                ps_res = root("ps -C php-fpm -o comm,args --no-headers | head -n 1 | awk '{print $1}'", check=False)
                fpm_bin = ps_res.stdout.strip() or "php-fpm"

            print(f"[✓] 實際運行的 FPM Binary: {fpm_bin}")

            # 3. 透過該 FPM binary 取得 FPM SAPI 專屬設定（非 CLI）
            print(f"[*] 查詢 FPM 核心配置路徑...")
            info_res = root(f"{shlex.quote(fpm_bin)} -i", check=True)
            phpinfo_text = info_res.stdout

            loaded_ini = None
            scan_dir = None
            for line in phpinfo_text.splitlines():
                if "Loaded Configuration File =>" in line:
                    loaded_ini = line.split("=>")[-1].strip()
                elif "Scan this dir for additional .ini files =>" in line:
                    scan_dir = line.split("=>")[-1].strip()

            print(f"[✓] FPM 載入的主要 php.ini: {loaded_ini}")
            print(f"[✓] FPM 額外 ini 掃描目錄 (conf.d): {scan_dir}")

            if not scan_dir or scan_dir == "(none)":
                target_ini_path = loaded_ini
                use_dropin = False
            else:
                target_ini_path = f"{scan_dir}/{DROP_IN_INI}"
                use_dropin = True

            print(f"[*] 預計套用緩解配置的位置: {target_ini_path} (Drop-in模式: {use_dropin})")

            # 4. 檢查現有 Pool 設定是否有衝突
            pool_conflicts = root(
                "grep -rE 'php_admin_(flag|value)\\[(session\\.upload_progress\\.enabled|file_uploads)\\]' /etc/php* 2>/dev/null || true",
                check=False
            ).stdout.strip()
            if pool_conflicts:
                print(f"[!] 注意：發現以下 Pool 設定含有覆蓋值：\n{pool_conflicts}")

            if dry_run:
                print("\n[!] Dry-run 模式結束，未更動任何檔案。")
                return

            # 5. 寫入 Drop-in 設定檔
            mitigation_content = (
                "; Generated by OpsFeast Mitigation for CVE-2026-109618 & CVE-2026-109619\n"
                "[PHP]\n"
                "session.upload_progress.enabled = Off\n"
                "file_uploads = Off\n"
            )
            escaped_content = shlex.quote(mitigation_content)
            root(f"echo {escaped_content} > {shlex.quote(target_ini_path)}", check=True)
            root(f"chmod 644 {shlex.quote(target_ini_path)}", check=True)
            print(f"[✓] 成功寫入緩解設定至: {target_ini_path}")

            # 6. 使用 FPM 自身的語法測試 (-t) 驗證設定檔
            print(f"[*] 驗證 FPM 設定語法...")
            test_res = root(f"{shlex.quote(fpm_bin)} -t", check=False)
            if test_res.exitcode != 0:
                print(f"[✗] 設定語法檢查失敗，自動復原！\n{test_res.stderr}", file=sys.stderr)
                root(f"rm -f {shlex.quote(target_ini_path)}", check=True)
                sys.exit(1)
            print(f"[✓] FPM 設定語法檢查通過")

            # 7. 重載 FPM 服務（加上 --no-pager）
            print(f"[*] 重載服務 {fpm_service}...")
            root(f"systemctl --no-pager reload {shlex.quote(fpm_service)}", check=True)
            print(f"[✓] 服務重載完成")

            # 8. 驗證最終生效值
            verify_res = root(
                f"{shlex.quote(fpm_bin)} -i | grep -E '(session\\.upload_progress\\.enabled|file_uploads) =>'",
                check=True
            )
            print(f"\n[✓] FPM SAPI 最終生效狀態：\n{verify_res.stdout.strip()}")
            print(f"\n[🎉] {TARGET_HOST} 的 PHP-FPM 緩解修補已成功且安全地生效！")


if __name__ == "__main__":
    is_dry_run = "--dry-run" in sys.argv
    #is_dry_run = True
    run_fpm_mitigation(dry_run=is_dry_run)

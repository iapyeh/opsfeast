#!/usr/bin/env python3
"""
專為 FreeBSD (myrpki2) 設計：精確針對 PHP-FPM 進行 CVE-2026-109618 / CVE-2026-109619 緩解修補
"""

import sys
import shlex
import re
from opsfeast import Instance, RootUnavailableError

TARGET_HOST = "myrpki2"
DROP_IN_INI = "99-security-cve-mitigation.ini"

def run_freebsd_mitigation(dry_run: bool = False):
    print(f"[*] 正在初始化 OpsFeast Instance...")
    instance = Instance.open(".")
    profile = instance.profile()
    print(f"[*] 使用 Profile: {profile.name} (連線目標: {TARGET_HOST})")
    print(f"[*] 執行模式: {'[DRY RUN - 僅檢查]' if dry_run else '[正式修補]'}\n")

    with profile.recipe(TARGET_HOST, timeout=60) as recipe:
        with recipe.root() as root:
            # 確保環境無分頁器干擾
            root("export PAGER=cat", check=False)

            # 1. 檢查 FreeBSD rc.d 服務狀態
            # 支援 php-fpm 或 php81-fpm
            print(f"[*] 檢查 FreeBSD 服務狀態...")
            svc_check = root(
                "service php-fpm status 2>/dev/null || service php81-fpm status 2>/dev/null || echo 'not_running'",
                check=False
            )
            svc_output = svc_check.stdout.strip()
            if "not_running" in svc_output or "cannot" in svc_output.lower():
                raise RuntimeError(f"未偵測到運行的 php-fpm 服務: {svc_output}")

            # 確定服務名稱（通常為 php-fpm）
            fpm_service = "php-fpm" if "php_fpm" in svc_output or "php-fpm" in svc_output else "php81-fpm"
            print(f"[✓] 偵測到 FreeBSD 活躍服務: {fpm_service} ({svc_output})")

            # 2. 定位 FreeBSD 的 php-fpm binary 路徑
            bin_check = root("which php-fpm || which /usr/local/sbin/php-fpm", check=False)
            fpm_bin = bin_check.stdout.strip() or "/usr/local/sbin/php-fpm"
            print(f"[✓] 實際運行的 FPM Binary: {fpm_bin}")

            # 3. 透過 FPM SAPI 獲取真正的設定路徑
            print(f"[*] 查詢 FreeBSD FPM 核心配置路徑...")
            info_res = root(f"{shlex.quote(fpm_bin)} -i", check=True)
            phpinfo_text = info_res.stdout

            loaded_ini = None
            scan_dir = None
            for line in phpinfo_text.splitlines():
                if "Loaded Configuration File =>" in line:
                    loaded_ini = line.split("=>")[-1].strip()
                elif "Scan this dir for additional .ini files =>" in line:
                    scan_dir = line.split("=>")[-1].strip()

            print(f"[✓] FPM 主要設定檔: {loaded_ini}")
            print(f"[✓] FPM 額外 ini 掃描目錄 (FreeBSD Ports): {scan_dir}")

            # FreeBSD 常見掃描目錄為 /usr/local/etc/php
            if not scan_dir or scan_dir == "(none)":
                target_ini_path = loaded_ini if (loaded_ini and loaded_ini != "(none)") else "/usr/local/etc/php.ini"
                use_dropin = False
            else:
                target_ini_path = f"{scan_dir}/{DROP_IN_INI}"
                use_dropin = True

            print(f"[*] 預計套用緩解配置路徑: {target_ini_path} (Drop-in模式: {use_dropin})")

            # 4. 檢查 FreeBSD /usr/local/etc/php-fpm.d/ 下是否有衝突的 Pool 設定
            pool_conflicts = root(
                "grep -rE 'php_admin_(flag|value)\\[(session\\.upload_progress\\.enabled|file_uploads)\\]' "
                "/usr/local/etc/php* 2>/dev/null || true",
                check=False
            ).stdout.strip()
            if pool_conflicts:
                print(f"[!] 注意：發現以下 Pool 設定含有覆蓋值：\n{pool_conflicts}")

            if dry_run:
                print("\n[!] Dry-run 模式結束，未更動任何檔案。")
                return

            # 5. 寫入緩解配置
            mitigation_content = (
                "; Generated by OpsFeast Mitigation for CVE-2026-109618 & CVE-2026-109619\n"
                "[PHP]\n"
                "session.upload_progress.enabled = Off\n"
                "file_uploads = Off\n"
            )
            escaped_content = shlex.quote(mitigation_content)

            # 若不是 drop-in 而是修改現有 ini，則進行追加/替換；若是 drop-in 則直接寫入檔案
            if use_dropin:
                root(f"echo {escaped_content} > {shlex.quote(target_ini_path)}", check=True)
            else:
                # 備份主要 ini
                root(f"cp -p {shlex.quote(target_ini_path)} {shlex.quote(target_ini_path)}.bak.$(date +%Y%m%d%H%M%S)", check=False)
                root(f"echo {escaped_content} >> {shlex.quote(target_ini_path)}", check=True)

            root(f"chmod 644 {shlex.quote(target_ini_path)}", check=True)
            print(f"[✓] 成功寫入緩解設定至: {target_ini_path}")

            # 6. 使用 FPM -t 進行設定檔語法測試
            print(f"[*] 測試 FPM 設定檔語法...")
            test_res = root(f"{shlex.quote(fpm_bin)} -t", check=False)
            if test_res.exitcode != 0:
                print(f"[✗] 設定檔語法錯誤，立即自動還原！\n{test_res.stderr}", file=sys.stderr)
                if use_dropin:
                    root(f"rm -f {shlex.quote(target_ini_path)}", check=True)
                sys.exit(1)
            print(f"[✓] FreeBSD FPM 設定檔語法測試正常")

            # 7. 重載 FreeBSD 服務 (service php-fpm reload)
            print(f"[*] 透過 FreeBSD service 重載 {fpm_service}...")
            reload_res = root(f"service {shlex.quote(fpm_service)} reload", check=False)
            if reload_res.exitcode != 0:
                print(f"[!] reload 回傳非零，嘗試 restart...")
                root(f"service {shlex.quote(fpm_service)} restart", check=True)
            print(f"[✓] 服務重載/重啟完成")

            # 8. 驗證新設定生效
            verify_res = root(
                f"{shlex.quote(fpm_bin)} -i | grep -E '(session\\.upload_progress\\.enabled|file_uploads) =>'",
                check=True
            )
            print(f"\n[✓] FPM SAPI 最終生效狀態：\n{verify_res.stdout.strip()}")
            print(f"\n[🎉] {TARGET_HOST} (FreeBSD) 的 PHP-FPM 緩解修補已成功且安全地生效！")

if __name__ == "__main__":
    is_dry_run = "--dry-run" in sys.argv
    #is_dry_run = 1
    run_freebsd_mitigation(dry_run=is_dry_run)

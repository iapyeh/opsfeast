"""Vault content application: structure and owned Markdown publication."""
import argparse
import hashlib
import json
from pathlib import Path
import shlex
from urllib.parse import quote
from contextlib import contextmanager
from opsfeast import ConfigError, Validator, resolve_root, __file__ as PACKAGE_FILE
from retention_store import atomic, checked, component, canonical, now, settings, reject_old_layout
from display_time import format_time
from vault_content import text, host_location

NOTICE = '> Automatically generated by OpsFeast. Do not edit; regeneration overwrites this file.\n\n'


def vault_checked(root, *parts):
    return checked(root, 'vault', *parts)


@contextmanager
def locked(root):
    import fcntl
    import os
    descriptor = os.open(checked(root, '.vault.lock'), os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
    with os.fdopen(descriptor, 'w') as stream:
        fcntl.flock(stream.fileno(), fcntl.LOCK_EX)
        yield


def generated(path, content, *, rebuild_root=None):
    guidance = ''
    if rebuild_root is not None:
        command = 'cd ' + shlex.quote(str(Path(PACKAGE_FILE).resolve().parents[1])) + ' && ' + shlex.join(
            ['python3', '-B', '-m', 'opsfeast', 'vault', 'rebuild', '--root', str(Path(rebuild_root).resolve()), '--json'])
        guidance = 'To regenerate this view, run:\n\n```sh\n' + command + '\n```\n\n'
    atomic(path, NOTICE + guidance + content + '\n\n_Last modified: ' + format_time(now()) + '_\n')


def publish(root, owner, entries):
    """Publish owned Markdown, replacing edits while protecting unowned paths.

    Caller holds the vault lock. Owner must be a simple stable author identifier.
    """
    import re
    if not isinstance(owner, str) or not re.fullmatch(r'[a-z][a-z0-9_-]*', owner):
        raise ConfigError('invalid content owner')
    manifest = vault_checked(root, '.content-' + owner + '.json')
    old = json.loads(manifest.read_text()) if manifest.exists() else {}
    if not isinstance(old, dict):
        raise ConfigError('invalid content ownership manifest')
    others = set()
    directory = vault_checked(root)
    for other in directory.glob('.content-*.json') if directory.exists() else ():
        if other != manifest:
            checked_other = vault_checked(root, other.name)
            data = json.loads(checked_other.read_text())
            if not isinstance(data, dict):
                raise ConfigError('invalid content ownership manifest')
            others.update(data)
    for name in set(old) | set(entries):
        if not isinstance(name, str) or not name.endswith('.md'):
            raise ConfigError('content outputs must be relative Markdown paths')
        path = vault_checked(root, *name.split('/'))
        if name in others:
            raise ConfigError('content output belongs to another author')
        if path.exists() and name not in old:
            raise ConfigError('content output collides with unmanaged file: ' + name)
    # Record ownership of each successful write so interrupted publication is repairable.
    owned = dict(old)
    for name, body in entries.items():
        path = vault_checked(root, *name.split('/'))
        generated(path, body, rebuild_root=root if name in ('HOSTS.md', 'overview/README.md') else None)
        owned[name] = hashlib.sha256(path.read_bytes()).hexdigest()
        atomic(manifest, canonical(owned) + '\n')
    for name in old.keys() - entries.keys():
        vault_checked(root, *name.split('/')).unlink(missing_ok=True)
        owned.pop(name)
        atomic(manifest, canonical(owned) + '\n')
    return {'status': 'success', 'owner': owner, 'files': sorted(entries)}


def rebuild_unlocked(root):
    reject_old_layout(root)
    if settings(root) is None:
        raise ConfigError('vault requires a namespace; initialize the profile first')
    from vault_content import build
    runtime = Validator(Path(root))
    runtime.load(Path(root) / 'hosts.yaml')
    entries, index, hosts = build(root, runtime)
    # Structure indexes are platform-owned; observation pages belong to the bundled author.
    publish(root, 'structure', {'HOSTS.md': '\n'.join(index),
            'overview/README.md': '\n'.join(index).replace('](hosts/', '](../hosts/')})
    publish(root, 'bundled-retention', entries)
    for host in hosts:
        path = vault_checked(root, *host_location(runtime, host).split('/'), 'README.md')
        if not path.exists():
            atomic(path, '# ' + text(host) + '\n\n[Known state](records/README.md)\n\nHuman notes may be added here.\n\n_Last modified: ' + format_time(now()) + '_\n')
    landing = vault_checked(root, 'README.md')
    if not landing.exists():
        atomic(landing, '# Feast host vault\n\n[All hosts](HOSTS.md)\n\n[Groups](groups/README.md)\n\nHuman notes may be added here.\n\n_Last modified: ' + format_time(now()) + '_\n')
    from retention_store import query
    return {'status': 'success', 'vault_directory': str(vault_checked(root)), 'hosts': len(hosts), 'records': len(query(root)['records'])}


def rebuild(root):
    with locked(root):
        result = rebuild_unlocked(root)
    refresh_groups(root)
    return result


def refresh_groups(root):
    with locked(root):
        runtime = Validator(Path(root))
        runtime.load(Path(root) / 'hosts.yaml')
        entries = {}
        for group, metadata in runtime.groups.items():
            folder = component(group)
            body = ['# ' + text(metadata.get('label', group)), '', 'Generated: ' + format_time(now()), '']
            for host in metadata['hosts']:
                filename = component(host) + '.md'
                target = '../../' + host_location(runtime, host) + '/README.md'
                entries['groups/' + folder + '/' + filename] = '# ' + text(host) + '\n\n[Host](' + quote(target, safe='/') + ')'
                body.append('- [' + text(host) + '](' + quote(filename) + ')')
            entries['groups/' + folder + '/README.md'] = '\n'.join(body)
        entries['groups/README.md'] = '# Groups\n\n' + '\n'.join(
            '- [' + text(name) + '](' + quote(component(name) + '/README.md', safe='/') + ')'
            for name in sorted(runtime.groups))
        publish(root, 'groups', entries)
        return {'status': 'success', 'groups': len(runtime.groups)}


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog='opsfeast.py vault',
        description=('Maintain local Markdown views of retained observations and operation evidence.\n'
        'Rebuild replaces manifest-owned generated pages and preserves unmanaged human\n'
        'notes. This does not collect host data or change authoritative retention\n'
        'records.'),
        epilog=('Actions:\n'
        '  rebuild    Regenerate current Vault content and group links.\n'
        '  groups     Refresh group membership links only.\n'
        '  inspect    Read Vault settings and output location without publishing.\n'
        '\n'
        'Example: opsfeast.py vault rebuild --profile main --json'),
        formatter_class=argparse.RawDescriptionHelpFormatter, allow_abbrev=False)
    parser.add_argument('action', choices=('rebuild', 'groups', 'inspect'))
    location = parser.add_mutually_exclusive_group()
    location.add_argument('--root')
    location.add_argument('--profile')
    parser.add_argument('--json', action='store_true')
    args = parser.parse_args(argv)
    try:
        root = resolve_root(args.root, args.profile).resolve(strict=True)
        reject_old_layout(root)
        if args.action == 'rebuild':
            result = rebuild(root)
        elif args.action == 'groups':
            result = refresh_groups(root)
        else:
            result = {'status': 'success', 'settings': settings(root), 'vault_directory': str(vault_checked(root))}
        print(json.dumps(result, ensure_ascii=False))
        return 0
    except (ConfigError, OSError, ValueError) as exc:
        print(json.dumps({'status': 'failed', 'error_type': type(exc).__name__,
                          'message': str(exc) if isinstance(exc, ConfigError) else 'vault content update failed'}), file=__import__('sys').stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
